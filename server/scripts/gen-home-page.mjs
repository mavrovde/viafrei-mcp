// Writes src/content/home-page.ts from src/content/home-page.html: the page ships INSIDE the compiled module, so
// the image and the package carry it with no file copy and no read at runtime. `--check` fails when the module
// is out of date (test/home-page.test.ts runs the same comparison).
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/content/", import.meta.url);
const html = readFileSync(new URL("home-page.html", dir), "utf8");
const header = "// GENERATED by scripts/gen-home-page.mjs from home-page.html: edit the .html, then rerun it.\n";
const out = `${header}export const HOME_PAGE_HTML: string = ${JSON.stringify(html)};\n`;
const target = new URL("home-page.ts", dir);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("src/content/home-page.ts is out of date: run node scripts/gen-home-page.mjs");
    process.exit(1);
  }
} else writeFileSync(target, out);
