// Writes src/api/operations.ts from test/fixtures/api-openapi.json (the API's own document) and the proposed
// operations in test/fixtures/api-proposed.json (x-proposed, in no released API yet): every operation's method,
// path and parameter names, so the client never spells a path by hand. `--check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL("..", import.meta.url);
const spec = JSON.parse(readFileSync(new URL("test/fixtures/api-openapi.json", here), "utf8"));
const proposed = JSON.parse(readFileSync(new URL("test/fixtures/api-proposed.json", here), "utf8"));
for (const [path, item] of Object.entries(proposed.paths)) {
  if (path in spec.paths) throw new Error(`${path} is in the API's document: drop it from api-proposed.json`);
  spec.paths[path] = item;
}
const params = spec.components?.parameters ?? {};
const ops = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (typeof op !== "object" || op === null || typeof op.operationId !== "string") continue;
    const all = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p) => (p.$ref ? params[p.$ref.split("/").pop()] : p));
    ops[op.operationId] = {
      method: method.toUpperCase(),
      path,
      pathParams: all.filter((p) => p.in === "path").map((p) => p.name),
      query: all.filter((p) => p.in === "query").map((p) => p.name),
      required: all.filter((p) => p.required === true).map((p) => p.name),
      // A proposed operation (x-proposed): no released API has it yet; the client asks it only once the API's
      // own OpenAPI document lists it.
      ...(op["x-proposed"] === true ? { proposed: true } : {}),
    };
  }
}
const body = `// Generated by scripts/gen-operations.mjs from test/fixtures/api-openapi.json (API ${spec.info.version}) and api-proposed.json. Do not edit.
export const API_CONTRACT_VERSION = ${JSON.stringify(spec.info.version)};
export const OPERATIONS = ${JSON.stringify(ops, null, 2)} as const;
export type OperationId = keyof typeof OPERATIONS;
`;
const target = new URL("src/api/operations.ts", here);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== body) {
    console.error("src/api/operations.ts is out of date: run node scripts/gen-operations.mjs");
    process.exit(1);
  }
} else writeFileSync(target, body);
